// scripts/generate-city-data.mjs
//
// Turns the map (data/cityMap.mjs) into engine/city_data.h, so the C++ engine
// routes on exactly the city the frontend draws: the same nodes, the same 84
// roads, the same road lengths and capacities.
//
//   node scripts/generate-city-data.mjs
//   node scripts/generate-city-data.mjs <path to cityMap.mjs> <path to city_data.h>
//
// Run it again whenever data/cityMap.mjs changes, then rebuild the engine
// (npm run build:engine).

import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataPath = process.argv[2] || path.join(here, "..", "data", "cityMap.mjs");
const outPath = process.argv[3] || path.join(here, "..", "engine", "city_data.h");

const data = await import(pathToFileURL(dataPath).href);

const { NODES, GRAPH_EDGES, MAP_GEO } = data;
if (!NODES || !GRAPH_EDGES || !MAP_GEO) {
  throw new Error("cityMap.mjs must export NODES, GRAPH_EDGES and MAP_GEO");
}

const s = (value) => JSON.stringify(String(value));

const nodeLines = NODES.map(
  (n) =>
    `    {${s(n.id)}, ${s(n.name)}, ${Math.round(n.x)}, ${Math.round(n.y)}, ${s(n.kind)}, ${s(n.stationType || "")}},`
);

const roadLines = GRAPH_EDGES.map(
  (e) =>
    `    {${s(e.id)}, ${s(e.u)}, ${s(e.v)}, ${e.weight}, ${e.capacity}, ${e.isMajor ? "true" : "false"}, ${e.isShortcut ? "true" : "false"}},`
);

const text = `// engine/city_data.h
//
// GENERATED by scripts/generate-city-data.mjs from data/cityMap.mjs. Do not edit
// by hand: change the map in data/cityMap.mjs, then run
//     node scripts/generate-city-data.mjs && npm run build:engine
//
// ${NODES.length} nodes, ${GRAPH_EDGES.length} roads.
#pragma once

struct CityNode
{
    const char* id;
    const char* name;
    int x;
    int y;
    const char* kind;          // "junction" (a locality) or "station"
    const char* stationType;   // "hospital" | "police" | "fire", empty for junctions
};

struct CityRoad
{
    const char* id;            // "<from>-<to>", the key used in the traffic object
    const char* from;
    const char* to;
    int weight;                // road length in map units, 1 unit = 0.045 km
    int capacity;              // vehicles the road holds before it is over capacity
    bool major;
    bool shortcut;
};

// how the map's x / y pixels convert to latitude / longitude
const double MAP_REF_X = ${MAP_GEO.refX};
const double MAP_REF_Y = ${MAP_GEO.refY};
const double MAP_REF_LAT = ${MAP_GEO.refLat};
const double MAP_REF_LNG = ${MAP_GEO.refLng};
const double MAP_LAT_PER_PX = ${MAP_GEO.latPerPx};
const double MAP_LNG_PER_PX = ${MAP_GEO.lngPerPx};

static const CityNode CITY_NODES[] = {
${nodeLines.join("\n")}
};

static const CityRoad CITY_ROADS[] = {
${roadLines.join("\n")}
};

const int CITY_NODE_COUNT = sizeof(CITY_NODES) / sizeof(CITY_NODES[0]);
const int CITY_ROAD_COUNT = sizeof(CITY_ROADS) / sizeof(CITY_ROADS[0]);
`;

fs.writeFileSync(outPath, text);
console.log("Wrote " + outPath + " (" + NODES.length + " nodes, " + GRAPH_EDGES.length + " roads)");
